import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

import { fetchLibrarySourceDoc, readInstalledLibraryVersion } from './library-docs.mjs';

/**
 * Generates `src/app/generated/library-tables/<slug>.generated.ts` from the library docs at the
 * installed release tag: the "Color Tokens" and "Geometry Tokens" tables, and the defaults key and
 * option table of the "Provider Defaults" section. Component pages render these rows through
 * `app-token-tables-section` and `app-provider-defaults-section`, so a sync only has to regenerate
 * them. Needs network access to GitHub raw (like `generate-agent-surface`); `--check` fails when
 * the committed output differs.
 */
const PROJECT_ROOT = process.cwd();
const COMPONENTS_ROOT = join(PROJECT_ROOT, 'src', 'app', 'pages', 'components');
const OUTPUT_ROOT = join(PROJECT_ROOT, 'src', 'app', 'generated', 'library-tables');
const CHECK_MODE = process.argv.includes('--check');
const TOKEN_TABLE_KINDS = [
  { marker: 'color-tokens', suffix: 'COLOR_TOKEN_ROWS' },
  { marker: 'geometry-tokens', suffix: 'GEOMETRY_TOKEN_ROWS' },
];

const version = await readInstalledLibraryVersion(PROJECT_ROOT);
const slugs = readdirSync(COMPONENTS_ROOT, { withFileTypes: true })
  .filter(
    (entry) =>
      entry.isDirectory() &&
      existsSync(join(COMPONENTS_ROOT, entry.name, `${entry.name}.docs-manifest.ts`)),
  )
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right));

const outputs = new Map();

for (const slug of slugs) {
  const { content } = await fetchLibrarySourceDoc(version, slug);
  const exports = content === null ? [] : readExports(slug, content);

  if (exports.length > 0) {
    outputs.set(join(OUTPUT_ROOT, `${slug}.generated.ts`), renderModule(version, exports));
  }
}

const messageGroups = readMessageGroups(
  readFileSync(
    join(PROJECT_ROOT, 'node_modules', '@kikita-labs', 'ui', 'types', 'kikita-labs-ui.d.ts'),
    'utf8',
  ),
);

outputs.set(
  join(OUTPUT_ROOT, 'messages.generated.ts'),
  renderMessagesModule(version, messageGroups),
);

const staleOutputs = findStaleOutputs(outputs);

if (staleOutputs.length === 0) {
  console.log(`Generated library tables are current (${outputs.size} components, v${version}).`);
} else if (CHECK_MODE) {
  console.error(
    'Generated library tables are stale. Run "node tools/generate-library-tables.mjs".',
  );
  process.exitCode = 1;
} else {
  mkdirSync(OUTPUT_ROOT, { recursive: true });

  for (const [outputPath, output] of outputs) {
    writeFileSync(outputPath, output, 'utf8');
  }

  for (const staleOutput of staleOutputs.filter((outputPath) => !outputs.has(outputPath))) {
    rmSync(staleOutput);
  }

  console.log(`Generated library tables for ${outputs.size} components (v${version}).`);
}

/**
 * The `KuiMessages` groups of the installed typings: the group key and element note come from the
 * `KuiMessages` interface, the member rows (name, type, default text) from each group interface.
 */
function readMessageGroups(declarations) {
  const root = /^interface KuiMessages \{\n([\s\S]*?)\n\}/m.exec(declarations);

  if (!root) {
    throw new Error('KuiMessages interface not found in the installed typings.');
  }

  return [...root[1].matchAll(/\/\*\*\s*([^*]*?)\s*\*\/\s*readonly (\w+): (Kui\w+Messages);/g)].map(
    ([, note, group, interfaceName]) => {
      const body = new RegExp(`^interface ${interfaceName} \\{\\n([\\s\\S]*?)\\n\\}`, 'm').exec(
        declarations,
      );

      if (!body) {
        throw new Error(`${interfaceName} not found in the installed typings.`);
      }

      const rows = [
        ...`${body[1]}
`.matchAll(/\/\*\*([\s\S]*?)\*\/\s*readonly (\w+): ([\s\S]*?);\n(?=\s*(?:\/\*\*|$))/g),
      ].map(([, doc, name, type]) => ({
        name,
        type: type.replace(/\s+/g, ' ').trim(),
        description: plainText(doc.replace(/^\s*\*\s?/gm, ' ')),
      }));

      return { group, interfaceName, note: plainText(note), rows };
    },
  );
}

function plainText(text) {
  return text
    .replace(/\{@link\s+(\w+)\}/g, '$1')
    .replace(/\s+/g, ' ')
    .replaceAll('`', '')
    .trim();
}

function renderMessagesModule(libraryVersion, groups) {
  const body = groups
    .map(
      (group) =>
        `export const ${group.group.replace(/([A-Z])/g, '_$1').toUpperCase()}_MESSAGES: MessagesGroup = {\n  group: ${quote(group.group)},\n  interfaceName: ${quote(group.interfaceName)},\n  note: ${quote(group.note)},\n  rows: [\n${renderRows(group.rows, '    ')}\n  ],\n};\n`,
    )
    .join('\n');

  return `// Generated by tools/generate-library-tables.mjs from the @kikita-labs/ui v${libraryVersion} typings. Do not edit.\nimport { type MessagesGroup } from '@shared/docs-ui/messages-section';\n\n${body}`;
}

/** Returns `{ name, kind, value }` records, one per generated constant of a component. */
function readExports(slug, markdown) {
  const prefix = slug.toUpperCase().replaceAll('-', '_');
  const records = [];

  for (const { marker, suffix } of TOKEN_TABLE_KINDS) {
    const block = new RegExp(`<!-- ${marker}:begin -->([\\s\\S]*?)<!-- ${marker}:end -->`).exec(
      markdown,
    );
    const rows = block
      ? parseTable(block[1], /^--kui-/, ['name', 'defaultValue', 'description'])
      : [];

    if (rows.length > 0) {
      records.push({
        name: `${prefix}_${suffix}`,
        kind: 'rows',
        value: rows.map((row) => ({ ...row, type: 'CSS custom property' })),
      });
    }
  }

  const defaults = readProviderDefaults(markdown);

  if (defaults.length > 0) {
    records.push({ name: `${prefix}_DEFAULTS`, kind: 'groups', value: defaults });
  }

  return records;
}

/**
 * The `defaults.<key>` groups of the "Provider Defaults" section: each key announced by a line such
 * as "Set `defaults.avatar` once" or "`defaults.field`:" owns the `| Option | Values | Description |`
 * table that follows it.
 */
function readProviderDefaults(markdown) {
  const heading = /^## Provider Defaults\s*$/m.exec(markdown);

  if (!heading) {
    return [];
  }

  const rest = markdown.slice(heading.index + heading[0].length);
  const next = /^## /m.exec(rest);
  const section = next ? rest.slice(0, next.index) : rest;
  const groups = [];
  let currentKey = null;
  let tableLines = [];

  const flush = () => {
    const rows = parseTable(tableLines.join('\n'), /^[A-Za-z]\w*$/, [
      'name',
      'type',
      'description',
    ]).filter((row) => row.name !== 'Option');

    if (currentKey && rows.length > 0) {
      groups.push({ key: currentKey, rows });
    }

    tableLines = [];
  };

  for (const line of section.split('\n')) {
    const trimmed = line.trim();

    if (trimmed.startsWith('|')) {
      tableLines.push(trimmed);
      continue;
    }

    flush();

    const announced = /^(?:Set )?`defaults\.(\w+)`(?::| once)/.exec(trimmed)?.[1];
    currentKey = announced ?? currentKey ?? /`defaults\.(\w+)`/.exec(trimmed)?.[1] ?? null;
  }

  flush();

  return groups;
}

/**
 * Reads markdown table rows whose first cell matches `firstCell`; the header and the separator row
 * do not match. Cells are mapped to `fields` in order and stripped of code ticks.
 */
function parseTable(block, firstCell, fields) {
  return block
    .split('\n')
    .filter((line) => line.trim().startsWith('|'))
    .map((line) => splitRow(line.trim()).map(stripCode))
    .filter((cells) => cells.length >= fields.length && firstCell.test(cells[0]))
    .map((cells) => Object.fromEntries(fields.map((field, index) => [field, cells[index]])));
}

/** Splits a table row on pipes that are not escaped (`\|` inside a cell stays a pipe). */
function splitRow(line) {
  return line
    .slice(1, -1)
    .split(/(?<!\\)\|/)
    .map((cell) => cell.replaceAll('\\|', '|'));
}

/** One plain-text cell: a whole-cell code span loses its ticks, links keep their text only. */
function stripCode(cell) {
  return cell
    .trim()
    .replace(/^`([^`]*)`$/, '$1')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replaceAll('`', '');
}

function renderModule(libraryVersion, records) {
  const body = records
    .map((record) =>
      record.kind === 'groups'
        ? `export const ${record.name}: readonly ProviderDefaultsGroup[] = [\n${record.value
            .map(
              (group) =>
                `  {\n    key: ${quote(group.key)},\n    rows: [\n${renderRows(group.rows, '      ')}\n    ],\n  },`,
            )
            .join('\n')}\n];\n`
        : `export const ${record.name}: readonly ApiTableRow[] = [\n${renderRows(record.value, '  ')}\n];\n`,
    )
    .join('\n');
  const imports = [
    // Same order the import sorter produces, so lint-staged never rewrites generated files.
    records.some((record) => record.kind === 'rows')
      ? "import { type ApiTableRow } from '@shared/docs-ui/api-table';\n"
      : '',
    records.some((record) => record.kind === 'groups')
      ? "import { type ProviderDefaultsGroup } from '@shared/docs-ui/provider-defaults-section';\n"
      : '',
  ].join('');

  return `// Generated by tools/generate-library-tables.mjs from the @kikita-labs/ui v${libraryVersion} docs. Do not edit.\n${imports}\n${body}`;
}

function renderRows(rows, indent) {
  return rows
    .map(
      (row) =>
        `${indent}{\n${indent}  name: ${quote(row.name)},\n${indent}  type: ${quote(row.type)},\n${
          row.defaultValue === undefined
            ? ''
            : `${indent}  defaultValue: ${quote(row.defaultValue)},\n`
        }${indent}  description: ${quote(row.description)},\n${indent}},`,
    )
    .join('\n');
}

function quote(value) {
  const escaped = value.replaceAll('\\', '\\\\');

  return value.includes("'") && !value.includes('"')
    ? `"${escaped}"`
    : `'${escaped.replaceAll("'", "\\'")}'`;
}

function findStaleOutputs(expectedOutputs) {
  const existing = existsSync(OUTPUT_ROOT)
    ? readdirSync(OUTPUT_ROOT)
        .filter((name) => name.endsWith('.generated.ts'))
        .map((name) => join(OUTPUT_ROOT, name))
    : [];
  const stale = [];

  for (const [outputPath, output] of expectedOutputs) {
    if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== output) {
      stale.push(outputPath);
    }
  }

  return [...stale, ...existing.filter((outputPath) => !expectedOutputs.has(outputPath))];
}
