import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import process from 'node:process';

import { fetchLibrarySourceDoc, readInstalledLibraryVersion } from './library-docs.mjs';

/**
 * Generates `src/app/generated/token-tables/<slug>.generated.ts` from the "Color Tokens" and
 * "Geometry Tokens" tables of the library docs at the installed release tag. Each component page
 * renders these rows instead of hand-copied token lists, so a sync only has to regenerate them.
 * Needs network access to GitHub raw (like `generate-agent-surface`); `--check` fails when the
 * committed output differs.
 */
const PROJECT_ROOT = process.cwd();
const COMPONENTS_ROOT = join(PROJECT_ROOT, 'src', 'app', 'pages', 'components');
const OUTPUT_ROOT = join(PROJECT_ROOT, 'src', 'app', 'generated', 'token-tables');
const CHECK_MODE = process.argv.includes('--check');
const TABLE_KINDS = [
  { marker: 'color-tokens', suffix: 'COLOR_TOKEN_ROWS' },
  { marker: 'geometry-tokens', suffix: 'GEOMETRY_TOKEN_ROWS' },
];

const version = await readInstalledLibraryVersion(PROJECT_ROOT);
const slugs = readdirSync(COMPONENTS_ROOT, { withFileTypes: true })
  .filter(
    (entry) =>
      entry.isDirectory() &&
      existsSync(join(COMPONENTS_ROOT, entry.name, `${entry.name}.docs-manifest.ts`)),
  )
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right));

const outputs = new Map();

for (const slug of slugs) {
  const { content } = await fetchLibrarySourceDoc(version, slug);
  const tables = content === null ? [] : readTokenTables(content);

  if (tables.some((table) => table.rows.length > 0)) {
    outputs.set(join(OUTPUT_ROOT, `${slug}.generated.ts`), renderModule(slug, version, tables));
  }
}

const staleOutputs = findStaleOutputs(outputs);

if (staleOutputs.length === 0) {
  console.log(`Generated token tables are current (${outputs.size} components, v${version}).`);
} else if (CHECK_MODE) {
  console.error('Generated token tables are stale. Run "node tools/generate-token-tables.mjs".');
  process.exitCode = 1;
} else {
  mkdirSync(OUTPUT_ROOT, { recursive: true });

  for (const [outputPath, output] of outputs) {
    writeFileSync(outputPath, output, 'utf8');
  }

  for (const staleOutput of staleOutputs.filter((outputPath) => !outputs.has(outputPath))) {
    rmSync(staleOutput);
  }

  console.log(`Generated token tables for ${outputs.size} components (v${version}).`);
}

function readTokenTables(markdown) {
  return TABLE_KINDS.map(({ marker, suffix }) => {
    const block = new RegExp(`<!-- ${marker}:begin -->([\\s\\S]*?)<!-- ${marker}:end -->`).exec(
      markdown,
    );

    return { suffix, rows: block ? parseTable(block[1]) : [] };
  });
}

/** Reads `| Token | Default | Controls |` rows; the header and the separator row are skipped. */
function parseTable(block) {
  return block
    .split('\n')
    .filter((line) => line.trim().startsWith('|'))
    .map((line) => line.trim().slice(1, -1).split('|').map(stripCode))
    .filter((cells) => cells.length >= 3 && /^--kui-/.test(cells[0]))
    .map(([name, defaultValue, controls]) => ({ name, defaultValue, controls }));
}

function stripCode(cell) {
  return cell.trim().replace(/^`(.*)`$/, '$1');
}

function renderModule(slug, libraryVersion, tables) {
  const prefix = slug.toUpperCase().replaceAll('-', '_');
  const exports = tables
    .filter((table) => table.rows.length > 0)
    .map((table) => {
      const rows = table.rows
        .map(
          (row) =>
            `  {\n    name: ${quote(row.name)},\n    type: 'CSS custom property',\n    defaultValue: ${quote(row.defaultValue)},\n    description: ${quote(row.controls)},\n  },`,
        )
        .join('\n');

      return `export const ${prefix}_${table.suffix}: readonly ApiTableRow[] = [\n${rows}\n];\n`;
    })
    .join('\n');

  return `// Generated by tools/generate-token-tables.mjs from the @kikita-labs/ui v${libraryVersion} docs. Do not edit.\nimport { type ApiTableRow } from '@shared/docs-ui/api-table';\n\n${exports}`;
}

function quote(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function findStaleOutputs(expectedOutputs) {
  const existing = existsSync(OUTPUT_ROOT)
    ? readdirSync(OUTPUT_ROOT)
        .filter((name) => name.endsWith('.generated.ts'))
        .map((name) => join(OUTPUT_ROOT, name))
    : [];
  const stale = [];

  for (const [outputPath, output] of expectedOutputs) {
    if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== output) {
      stale.push(outputPath);
    }
  }

  return [...stale, ...existing.filter((outputPath) => !expectedOutputs.has(outputPath))];
}
